import type { ExpoConfig } from 'expo/config';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

// Expo's config loader can't import TypeScript modules, so read the brand color from tokens.ts as text.
const tokens = readFileSync(join(__dirname, 'src/theme/tokens.ts'), 'utf8');
const brand = /^\s*brand: '(#[0-9a-f]{6})'/m.exec(tokens)?.[1];
if (!brand) throw new Error('colors.brand not found in src/theme/tokens.ts');
const colors = { brand };

// Permission prompts use the app's copy from en.json (AGENTS rule 13).
const en = JSON.parse(readFileSync(join(__dirname, 'src/i18n/en.json'), 'utf8')) as {
  camera: { permissionDescription: string };
  gallery: { permissionDescription: string };
};

// Brand colors come from tokens.ts; image files are generated by scripts/gen-brand-assets.sh.
const config: ExpoConfig = {
  name: 'Pickld',
  slug: 'pickld',
  version: '2.0.0',
  orientation: 'portrait',
  scheme: 'pickld',
  userInterfaceStyle: 'light',
  icon: './assets/brand/icon.png',
  ios: {
    bundleIdentifier: 'me.pickld.app',
    supportsTablet: false,
    icon: './assets/brand/icon.png',
    infoPlist: {
      NSCameraUsageDescription: en.camera.permissionDescription,
      NSPhotoLibraryUsageDescription: en.gallery.permissionDescription,
    },
  },
  android: {
    package: 'me.pickld.app',
    predictiveBackGestureEnabled: false,
    permissions: ['android.permission.CAMERA'],
    adaptiveIcon: {
      backgroundColor: colors.brand,
      foregroundImage: './assets/brand/android-foreground.png',
      monochromeImage: './assets/brand/android-monochrome.png',
    },
  },
  web: { bundler: 'metro', output: 'static' },
  plugins: [
    'expo-router',
    'expo-font',
    'expo-localization',
    'expo-secure-store',
    'expo-sqlite',
    // Local slot reminders and server pushes (FR-NOT-01, FR-NOT-02).
    ['expo-notifications', { color: colors.brand }],
    // The gallery picker (D-26): only the photo library; the camera is vision-camera's, no microphone.
    [
      'expo-image-picker',
      {
        photosPermission: en.gallery.permissionDescription,
        cameraPermission: en.camera.permissionDescription,
        microphonePermission: false,
      },
    ],
    [
      'expo-splash-screen',
      {
        backgroundColor: colors.brand,
        image: './assets/brand/splash-logo.png',
        imageWidth: 220,
        resizeMode: 'contain',
      },
    ],
  ],
  experiments: { typedRoutes: true, reactCompiler: true },
};

export default config;
