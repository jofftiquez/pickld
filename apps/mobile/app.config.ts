import type { ExpoConfig } from 'expo/config';
import { execSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

// Expo's config loader can't import TypeScript modules, so read the brand color from tokens.ts as text.
const tokens = readFileSync(join(__dirname, 'src/theme/tokens.ts'), 'utf8');
const brand = /^\s*brand: '(#[0-9a-f]{6})'/m.exec(tokens)?.[1];
if (!brand) throw new Error('colors.brand not found in src/theme/tokens.ts');
const colors = { brand };
// The native launch image's box (D-147): splash.canvasHeight square, so the image shows at its point size.
const splashCanvasHeight = Number(/^\s*canvasHeight: (\d+),/m.exec(tokens)?.[1]);
if (!splashCanvasHeight) throw new Error('splash.canvasHeight not found in src/theme/tokens.ts');

// Permission prompts use the app's copy from en.json (AGENTS rule 13).
const en = JSON.parse(readFileSync(join(__dirname, 'src/i18n/en.json'), 'utf8')) as {
  camera: { permissionDescription: string };
  gallery: { permissionDescription: string };
  contacts: { permissionDescription: string };
  mediaLibrary: { savePermissionDescription: string };
  location: { permissionDescription: string };
  widgets: { todayName: string; todayDescription: string; friendName: string; friendDescription: string };
};

// `PICKLD_IOS_VARIANT=local npx expo prebuild` makes a second install that sits beside the store app on one
// phone: every bundle id and the App Group get `.local`, and plain http is allowed for a local backend. The
// share extension (targets/share) derives its host app and App Group from its own bundle id.
const localVariant = process.env.PICKLD_IOS_VARIANT === 'local';
const bundleId = localVariant ? 'me.pickld.app.local' : 'me.pickld.app';
const appGroup = `group.${bundleId}`;

// The shown version is `version-releaseTag.N`, e.g. 2.0.0-dev.1423; clear the tag for a store release. iOS
// needs `version` to stay plain X.Y.Z. N is the store build number on EAS (auto-incremented); local builds
// all have build number 1, so they use the git commit count, which expo-constants re-reads on every Xcode
// build even without a new prebuild.
const releaseTag = 'dev';
function commitCount(): string | undefined {
  if (process.env.EAS_BUILD) return undefined;
  try {
    return execSync('git rev-list --count HEAD', { cwd: __dirname, stdio: ['ignore', 'pipe', 'ignore'] })
      .toString()
      .trim();
  } catch {
    return undefined;
  }
}

